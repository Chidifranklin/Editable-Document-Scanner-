import { Document, Packer, Paragraph, TextRun, HeadingLevel } from 'docx';
import { jsPDF } from 'jspdf';

export async function exportToPdf(
  title: string,
  content: string,
  pages?: Array<{ pageNumber: number; text: string }>
): Promise<Blob> {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 20;
  const contentWidth = pageWidth - margin * 2;
  const bottomMargin = 22; // space for footer

  let y = margin;

  const drawRunningHeader = () => {
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(148, 163, 184); // slate-400
    const truncatedTitle = title.length > 40 ? title.substring(0, 37) + '...' : title;
    doc.text(truncatedTitle || 'Scanned Document', margin, margin - 6);
    doc.setDrawColor(226, 232, 240); // slate-200
    doc.setLineWidth(0.2);
    doc.line(margin, margin - 4, pageWidth - margin, margin - 4);
    y = margin;
  };

  const checkPageBreak = (neededHeight: number) => {
    if (y + neededHeight > pageHeight - bottomMargin) {
      doc.addPage();
      y = margin;
      drawRunningHeader();
    }
  };

  // 1. Draw Title Header on Page 1
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(18);
  doc.setTextColor(15, 23, 42); // slate-900
  const titleLines = doc.splitTextToSize(title || 'Scanned Document', contentWidth);
  doc.text(titleLines, margin, y);
  y += titleLines.length * 7 + 2;

  // Metadata subtitle
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(100, 116, 139); // slate-500
  const dateStr = new Date().toLocaleDateString(undefined, {
    year: 'numeric',
    month: 'short',
    day: 'numeric',
  });
  doc.text(`Generated by ScanText • ${dateStr}`, margin, y);
  y += 5;

  // Header separator line
  doc.setDrawColor(203, 213, 225); // slate-300
  doc.setLineWidth(0.4);
  doc.line(margin, y, pageWidth - margin, y);
  y += 7;

  // Helper to render formatted text maintaining document layout
  const renderFormattedText = (rawText: string, pageLabel?: string) => {
    if (pageLabel) {
      checkPageBreak(12);
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(12);
      doc.setTextColor(37, 99, 235); // blue-600
      doc.text(pageLabel, margin, y);
      y += 6;
      doc.setDrawColor(226, 232, 240);
      doc.setLineWidth(0.2);
      doc.line(margin, y - 1, margin + 40, y - 1);
      y += 4;
    }

    const lines = rawText.split('\n');

    for (let i = 0; i < lines.length; i++) {
      const line = lines[i];
      const trimmed = line.trim();

      // Empty line -> paragraph separation
      if (!trimmed) {
        y += 4;
        checkPageBreak(5);
        continue;
      }

      // Explicit page breaks (=== Page 2 === or --- Page 2 ---)
      const pageBreakMatch = trimmed.match(/^(?:===|---|###)\s*Page\s*(\d+)\s*(?:===|---|###)?$/i);
      if (pageBreakMatch) {
        doc.addPage();
        y = margin;
        drawRunningHeader();
        y += 2;
        doc.setFont('helvetica', 'bold');
        doc.setFontSize(12);
        doc.setTextColor(37, 99, 235);
        doc.text(`Page ${pageBreakMatch[1]}`, margin, y);
        y += 7;
        continue;
      }

      // Section Headings (Markdown # or lines ending with colon or short all-caps lines)
      const isHeader =
        trimmed.startsWith('#') ||
        (trimmed.endsWith(':') && trimmed.length < 50) ||
        (trimmed === trimmed.toUpperCase() && trimmed.length > 3 && trimmed.length < 45 && !trimmed.includes('$'));

      if (isHeader) {
        checkPageBreak(10);
        doc.setFont('helvetica', 'bold');
        doc.setFontSize(11);
        doc.setTextColor(30, 41, 59); // slate-800
        const headerText = trimmed.replace(/^#+\s*/, '');
        const wrappedHeader = doc.splitTextToSize(headerText, contentWidth);
        doc.text(wrappedHeader, margin, y);
        y += wrappedHeader.length * 5 + 2;
        continue;
      }

      // Bullet points (•, -, *, numbers)
      const isBullet = /^[•\-\*]\s+/.test(trimmed);
      const isNumbered = /^\d+[\.\)]\s+/.test(trimmed);

      if (isBullet || isNumbered) {
        checkPageBreak(6);
        doc.setFont('helvetica', 'normal');
        doc.setFontSize(10);
        doc.setTextColor(51, 65, 85); // slate-700

        const bulletMatch = trimmed.match(/^([•\-\*]|\d+[\.\)])\s+(.*)/);
        const prefix = bulletMatch ? bulletMatch[1] : '•';
        const rest = bulletMatch ? bulletMatch[2] : trimmed;

        doc.text(prefix, margin, y);
        const wrappedRest = doc.splitTextToSize(rest, contentWidth - 6);
        doc.text(wrappedRest, margin + 6, y);
        y += wrappedRest.length * 4.8 + 1;
        continue;
      }

      // Normal paragraph text
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(10);
      doc.setTextColor(51, 65, 85); // slate-700
      const wrapped = doc.splitTextToSize(line, contentWidth);
      checkPageBreak(wrapped.length * 4.8);
      doc.text(wrapped, margin, y);
      y += wrapped.length * 4.8 + 1;
    }
  };

  // If multi-page batch array provided
  if (pages && pages.length > 1) {
    pages.forEach((p, idx) => {
      if (idx > 0) {
        doc.addPage();
        y = margin;
        drawRunningHeader();
        y += 2;
      }
      renderFormattedText(p.text, `Page ${p.pageNumber || idx + 1}`);
    });
  } else {
    renderFormattedText(content);
  }

  // Draw Footers on ALL pages (Page X of Y)
  const totalPages = doc.getNumberOfPages();
  for (let p = 1; p <= totalPages; p++) {
    doc.setPage(p);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(148, 163, 184); // slate-400

    // Footer divider line
    doc.setDrawColor(226, 232, 240);
    doc.setLineWidth(0.2);
    doc.line(margin, pageHeight - 12, pageWidth - margin, pageHeight - 12);

    // Footer text
    doc.text('ScanText OCR Document', margin, pageHeight - 7);
    const pageNumText = `Page ${p} of ${totalPages}`;
    doc.text(pageNumText, pageWidth - margin - doc.getTextWidth(pageNumText), pageHeight - 7);
  }

  return doc.output('blob');
}

export async function exportMultiPageToPdf(
  title: string,
  pages: Array<{ pageNumber: number; text: string }>
): Promise<Blob> {
  return exportToPdf(title, '', pages);
}

export async function exportToDocx(title: string, content: string): Promise<Blob> {
  const lines = content.split('\n');
  const paragraphs = lines.map((line) => {
    return new Paragraph({
      children: [
        new TextRun({
          text: line,
          font: 'Calibri',
          size: 24, // 12pt font
        }),
      ],
      spacing: {
        after: line.trim() === '' ? 120 : 160,
        line: 276,
      },
    });
  });

  const doc = new Document({
    sections: [
      {
        properties: {},
        children: [
          new Paragraph({
            text: title || 'Scanned Document',
            heading: HeadingLevel.HEADING_1,
            spacing: { after: 300 },
          }),
          ...paragraphs,
        ],
      },
    ],
  });

  return await Packer.toBlob(doc);
}

export async function exportMultiPageToDocx(
  title: string,
  pages: Array<{ pageNumber: number; text: string }>
): Promise<Blob> {
  const sectionsChildren: Paragraph[] = [
    new Paragraph({
      text: title || 'Scanned Document',
      heading: HeadingLevel.HEADING_1,
      spacing: { after: 300 },
    }),
  ];

  pages.forEach((page, idx) => {
    sectionsChildren.push(
      new Paragraph({
        text: `Page ${page.pageNumber || idx + 1}`,
        heading: HeadingLevel.HEADING_2,
        pageBreakBefore: idx > 0,
        spacing: { before: 200, after: 150 },
      })
    );

    const lines = page.text.split('\n');
    lines.forEach((line) => {
      sectionsChildren.push(
        new Paragraph({
          children: [
            new TextRun({
              text: line,
              font: 'Calibri',
              size: 24,
            }),
          ],
          spacing: {
            after: line.trim() === '' ? 120 : 160,
            line: 276,
          },
        })
      );
    });
  });

  const doc = new Document({
    sections: [
      {
        properties: {},
        children: sectionsChildren,
      },
    ],
  });

  return await Packer.toBlob(doc);
}

export function exportToTxt(content: string): Blob {
  return new Blob([content], { type: 'text/plain;charset=utf-8' });
}

export function downloadBlob(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export async function copyToClipboard(text: string): Promise<boolean> {
  if (navigator.clipboard && window.isSecureContext) {
    await navigator.clipboard.writeText(text);
    return true;
  }
  // Fallback for older contexts
  const textArea = document.createElement('textarea');
  textArea.value = text;
  textArea.style.position = 'fixed';
  textArea.style.left = '-999999px';
  document.body.appendChild(textArea);
  textArea.focus();
  textArea.select();
  const successful = document.execCommand('copy');
  document.body.removeChild(textArea);
  return successful;
}

export async function shareContent(title: string, text: string): Promise<boolean> {
  if (navigator.share) {
    try {
      await navigator.share({
        title: title || 'ScanText Document',
        text: text,
      });
      return true;
    } catch (err: any) {
      if (err.name !== 'AbortError') {
        console.warn('Navigator share error:', err);
      }
      return false;
    }
  }
  return false;
}
